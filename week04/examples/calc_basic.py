# 第4回 例題1：print() で計算の結果を表示する
# " " がなければ「式」として計算され、" " があれば「文字列」としてそのまま表示される。

print(3 + 5)        # 8
print(10 - 4)       # 6
print("3 + 5")      # 3 + 5（文字なので計算されない）

print("---")

# 計算の記号（演算子）。記号はすべて半角で打つ。
print(7 + 2)        # 9   足す
print(7 - 2)        # 5   引く
print(7 * 2)        # 14  かける（× ではなく *）
print(7 / 2)        # 3.5 割る（÷ ではなく /）
print(7 // 2)       # 3   割った商（小数点以下は切り捨て）
print(7 % 2)        # 1   割ったあまり
print(2 ** 10)      # 1024  累乗（2 の 10 乗）

print("---")

# 計算の順番：( ) の中 → ** → * / // % → + -
print(2 + 3 * 4)      # 14（先に 3 * 4）
print((2 + 3) * 4)    # 20（先に ( ) の中）
print(10 - 2 - 3)     # 5（同じ順位は左から）
print(2 ** 3 * 2)     # 16（先に 2 ** 3 = 8）

print("---")

# 整数（int）と小数（float）。/ の結果は、割り切れても小数になる。
print(10 / 2)       # 5.0
print(10 // 2)      # 5
print(7 / 2)        # 3.5
print(1.5 + 2)      # 3.5
