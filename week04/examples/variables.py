# 第4回 例題2：変数（名前のついた箱）
# x = 5 は「x という箱に 5 を入れる」。= は「等しい」ではなく「入れる」。

x = 5
print(x)            # 5（箱の中身）
print(x + 2)        # 7

print("---")

# なぜ変数を使うのか：値段が変わっても、1行目だけ直せばよい
price = 120
print(price * 3)    # 360
print(price * 10)   # 1200
print(price + 50)   # 170

print("---")

# 変数の中身を追う（トレース）：第3回の手順Aをそのまま書いたもの
x = 2               # x: 2
x = x + 3           # x: 5（右の x + 3 を先に計算して、左の箱に入れる）
x = x * 2           # x: 10
print(x)            # 10

print("---")

# x = x + 1 の読み方：「x を 1 増やす」
x = 5
x = x + 1
print(x)            # 6

print("---")

# A：同じ箱に2回入れると、前の値は消える（上書き）
x = 5
x = 7
print(x)            # 7

# B：b = a は「その瞬間の a の値」をコピーする。あとで a を変えても b は変わらない
a = 3
b = a
a = 10
print(b)            # 3

print("---")

# 文字列も箱に入る。" " があれば文字列、なければ数。
name = "山形"
print(name)         # 山形（箱の中身）
print("name")       # name（文字列そのもの）

age = 18            # 数
word = "18"         # 文字列
print(age + 1)      # 19
