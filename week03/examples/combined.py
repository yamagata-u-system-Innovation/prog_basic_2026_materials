# 第3回 例題4：3つの構造の組み合わせ
# クラス全員の点数で、1人ずつ合否を判定する。
# [ ] でまとめたデータ（リスト）は第8回で扱う。今日は流れを読めれば十分。

scores = [85, 60, 59, 92]

for score in scores:          # 繰り返し：全員分
    if score >= 60:           # 分岐：60点以上かどうか
        print(score, "点：合格")
    else:
        print(score, "点：不合格")

print("全員の判定が終わりました")   # 順次：繰り返しが終わったあとに1回だけ
