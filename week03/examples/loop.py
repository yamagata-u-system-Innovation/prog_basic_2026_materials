# 第3回 例題3：繰り返し（同じ処理を、条件を満たす間くり返す）

# (1) 回数が決まっている繰り返し：for（第6回で詳しく扱う）
for i in range(3):
    print("こんにちは")

print("---")

# (2) 条件を満たす間くり返す：while
#     スライドのフローチャート「回数は10未満？」をそのままPythonにしたもの
count = 0
while count < 10:
    print("スクワット", count + 1, "回目")
    count = count + 1   # この行を消すと、永遠に終わらない（無限ループ）

print("終了")
