# 練習③　条件に合う数を数えよう
# ① 読む：表示される行は何行？ 最後の行は何？ 実行する前に紙に書く
# ② 変える：「3 の倍数」に変えて実行。何個になる？
# ③ 足す：合計 total も求めて、個数と合計を表示する
# ④ 試す：range(1, 101) にして、1〜100 で確かめる

count = 0                  # 個数の箱。最初は 0
for i in range(1, 31):     # i に 1〜30 が順に入る
    if i % 5 == 0:         # 5 で割ったあまりが 0 なら（5 の倍数なら）
        print(i)
        count = count + 1  # 個数を 1 増やす
print(f"5 の倍数は {count} 個")
