# 練習②　合計を書きかえよう
# ① 読む：表示される文を、実行する前に紙に書く
# ② 変える：range(1, 11) にして保存・実行。合計はいくつになる？
# ③ 足す：くり返しの中に print(f"i は {i}、total は {total}") を足して、変化を見る
# ④ 試す：1〜100 の合計を表示する。range の数をどう変える？

total = 0                  # 合計の箱。最初は 0
for i in range(1, 6):      # i に 1, 2, 3, 4, 5 が順に入る
    total = total + i      # 今の total に i を足して、total に入れなおす
print(f"合計は {total}")
